# Keep the original catalog, detailed variants and any previously stored user names.
PRODUCTS = list({p.casefold(): p for p in [*PRODUCTS, *(name for entries in ANIMAL_PRODUCT_LISTS.values() for name in entries)]}.values())

_PRODUCT_FLAGS = {species: {name.casefold(): flag for name, flag in entries.items()} for species, entries in ANIMAL_PRODUCT_LISTS.items()}
_FLAG_LABELS = {"*": "Ergänzung / Pflege / Nichtarzneimittel", "**": "Humanarzneimittel / mögliche Umwidmung", "?": "Variante / Zulassung prüfen"}


def product_suggestions(names, species):
    """Return all documentation choices, prioritizing the matching source list."""
    species = {"cat": "Katze", "katze": "Katze", "dog": "Hund", "hund": "Hund"}.get(species.strip().casefold(), "")
    items = []
    for name in names:
        key = name.casefold()
        memberships = {animal: entries[key] for animal, entries in _PRODUCT_FLAGS.items() if key in entries}
        # Existing variants are distinguished only by the literal animal name in the original label.
        if not memberships and " – " in name:
            suffix = key.split(" – ", 1)[1]
            for animal, word in (("Katze", "katzen"), ("Hund", "hunde")):
                if word in suffix:
                    memberships[animal] = ""
        labels = [animal + (" · " + _FLAG_LABELS[flag] if flag else "") for animal, flag in memberships.items()]
        hint = " / ".join(labels) + " · ungeprüft" if labels else "Altbestand / eigene Eingabe · ungeprüft"
        if species and memberships and species not in memberships:
            hint = "Nicht in der " + species + "-Liste · " + hint
        priority = 0 if species in memberships else 1 if not memberships else 2 if species else 0
        items.append((priority, name, hint))
    items.sort(key=lambda item: (item[0], item[1].casefold()))
    return [name for _, name, _ in items], {name: hint for _, name, hint in items}
